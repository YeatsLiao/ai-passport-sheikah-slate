"""Import selected original UI WAVs from the user-downloaded Sounds Resource ZIP.

Usage: python -B tools/import_botw_sfx.py ZIP_OR_EXTRACTED_DIRECTORY
Never extracts arbitrary archive paths or overwrites current audio mappings.
"""
import hashlib
import json
from pathlib import Path
import sys
import zipfile

ROOT=Path(__file__).resolve().parents[1]
SOURCE='https://sounds.spriters-resource.com/nintendo_switch/thelegendofzeldabreathofthewild/asset/405753/'
FILES={
    'move':'Sys_Pouch_CursolMove_03.wav',
    'ok':'Sys_Cmn_Decide_01.wav',
    'back':'Sys_Cmn_Cancel_01.wav',
    'invalid':'Sys_Do_Invalid.wav',
    'activate':'SheikerStoneOpen_04_light.wav',
    'close':'SheikerStoneClose_04.wav',
    'startup':'Sys_GameStart.wav',
    'page':'Sys_PauseMenu_PageSlide.wav',
    'menu':'Sys_Pouch_OpenSubWindow_00.wav',
    'equip':'Sys_ShortCut_EquipDecide.wav',
    'shutter':'Sys_Camera_Shutter.wav',
    'detect':'Sys_Camera_Detect.wav',
    'zoom':'Sys_Camera_ZoomEnd.wav',
    'sensor':'Sys_Item_SheikSensor.wav',
    'found':'BGM_LocationOpen_S.wav',
    'cryonis':'Sys_Item_IceMaker_Making.wav',
    'amiibo':'Amiibo_TouchEffect01.wav',
    'complete':'Sys_Challenge_Complete.wav',
    'switch_on':'Sys_SlideSwitch_On.wav',
    'switch_off':'Sys_SlideSwitch_Off.wav',
    'cursor':'SYS_CursorMove_Sub.wav',
    'lock':'Sys_MainScreen_Lockon.wav',
}

OPTIONAL={'magnet_catch': 'ReactionHit/SE_MagneCatch_Catch.wav', 'magnet_move': 'ReactionHit/SE_MagneCatch_Moving.wav', 'magnet_stop': 'ReactionHit/SE_MagneCatch_Stop.wav', 'magnet_release': 'ReactionHit/SE_MagneCatch_Disappear.wav', 'stasis_start': 'ReactionHit/Bitalock_Start_02.wav', 'stasis_hit': 'ReactionHit/Bitalock_Hit_06.wav', 'stasis_hit_end': 'ReactionHit/Bitalock_Hitend_06.wav', 'stasis_release_1': 'ReactionHit/Bitalock_End_06.wav', 'stasis_release_2': 'ReactionHit/Bitalock_End_07.wav', 'stasis_release_3': 'ReactionHit/Bitalock_End_08.wav', 'chest_open': 'TBox_Field_Wood/TboxFieldWood_Open.wav', 'ice_break': 'Obj_IceMakerBlock/IceMakerBlock_Crush.wav'}

if __name__=='__main__':
    if len(sys.argv)!=2:
        raise SystemExit('Usage: python -B tools/import_botw_sfx.py ZIP_OR_EXTRACTED_DIRECTORY')
    archive=Path(sys.argv[1])
    required={kind:'M_UI/'+name for kind,name in FILES.items()}
    required.update(boom='M_SceneStatic/RemoteBomb.wav',place='M_SceneStatic/Bomb_appear01.wav',unequip='M_SceneStatic/Sys_PauseMenu_UnEquip.wav',stasis_timer='ExpressionSound/BitaLock_Timer03.wav',item_get='GetItemSound/SYS_ItemGet_Common.wav')
    required.update(OPTIONAL)
    if archive.is_dir():
        candidates=list(archive.rglob('*.wav'))
        members={str(p.relative_to(archive)).replace('\\','/'):p for p in candidates}
        chosen={kind:next((name for name in members if name.endswith(path)),None) for kind,path in required.items()}
        missing=[required[k] for k,v in chosen.items() if v is None and k not in OPTIONAL]
        if missing:raise SystemExit('Missing source files: '+', '.join(missing))
        payload={kind:members[name].read_bytes() for kind,name in chosen.items() if name is not None}
    else:
        with zipfile.ZipFile(archive) as z:
            chosen={kind:next((name for name in z.namelist() if name.replace('\\','/').endswith(path)),None) for kind,path in required.items()}
            missing=[required[k] for k,v in chosen.items() if v is None and k not in OPTIONAL]
            if missing:raise SystemExit('Missing source files: '+', '.join(missing))
            payload={kind:z.read(name) for kind,name in chosen.items() if name is not None}
    records=[]
    dest=ROOT/'assets/audio/prototype/botw'
    for kind,data in payload.items():
        name=Path(required[kind]).name
        if len(data)<44 or data[:4]!=b'RIFF' or data[8:12]!=b'WAVE':
            raise SystemExit('Invalid WAV; nothing imported: '+name)
        target=dest/name
        if target.exists() and target.read_bytes()!=data:
            raise SystemExit('Existing different file: '+name)
        records.append(dict(kind=kind,file=name,archive_path=chosen[kind],source=('https://sounds.spriters-resource.com/nintendo_switch/thelegendofzeldabreathofthewild/asset/405754/' if kind in OPTIONAL else SOURCE),sha256=hashlib.sha256(data).hexdigest(),bytes=len(data)))
    dest.mkdir(parents=True,exist_ok=True)
    for record in records:(dest/record['file']).write_bytes(payload[record['kind']])
    (dest/'manifest.json').write_text(json.dumps(dict(source=SOURCE,submitter='Random Talking Bush',platform='Nintendo Switch',files=records),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (ROOT/'prototype/js/sound-files.js').write_text('/* Generated by tools/import_botw_sfx.py: only imported files. */\nconst BOTW_SFX_FILES='+json.dumps({r['kind']:r['file'] for r in records},indent=2)+';\n',encoding='utf-8')
    print(f'Imported {len(records)} original WAV files into assets/audio/prototype/botw; source bytes preserved.')
